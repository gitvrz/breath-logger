# PlatformIO pre-build step: writes src/build_info.cpp with the firmware's identity:
# version (config.h FW_VERSION), build date and git commit. Runs at every build, so
# two builds can always be told apart (the page shows it, the firmware update compares it).
# The FW_ID text also marks the file as a Breath Logger firmware: the page reads the
# version of a firmware file from it before installing it, the device refuses a file
# without it (ota.cpp).
import os
import re
import subprocess
import time

Import("env")  # noqa: F821 (provided by PlatformIO)

project = env["PROJECT_DIR"]  # noqa: F821
src = os.path.join(project, "src")
config = open(os.path.join(src, "config.h")).read()
version = re.search(r'#define\s+FW_VERSION\s+"([^"]+)"', config).group(1)


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=project, capture_output=True, text=True, timeout=5).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


commit = git("rev-parse", "--short", "HEAD")
if commit and git("status", "--porcelain", "--untracked-files=no"):
    commit += "+"  # built with changes not committed yet
build = time.strftime("%Y-%m-%d %H:%M:%S") + (f" {commit}" if commit else "")
if env["PIOENV"] != "esp32s3":  # noqa: F821 (a test firmware, e.g. crash-test)
    build += f" {env['PIOENV']}"  # noqa: F821

text = f"""// Generated by build_info.py at each build. Do not edit.
extern const char BUILD_ID[];
extern const char FW_ID[];
const char BUILD_ID[] = "{build}";
const char FW_ID[] = "#BreathLogger-firmware {version} {build}#";
"""
with open(os.path.join(src, "build_info.cpp"), "w") as f:
    f.write(text)
print(f"build_info: {version} {build}")
