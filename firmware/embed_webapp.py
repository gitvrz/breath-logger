# PlatformIO pre-build step: packs ../webapp (the web page) into src/webapp_files.h,
# gzipped, so the firmware serves the page over Wi-Fi (net.cpp). Runs at every build:
# the page served by the device is always the one the firmware was built with.
import gzip
import os

Import("env")  # noqa: F821 (provided by PlatformIO)

MIME = {
    ".html": "text/html", ".css": "text/css", ".js": "application/javascript",
    ".woff2": "font/woff2", ".svg": "image/svg+xml", ".png": "image/png",
    ".ico": "image/x-icon", ".json": "application/json",
}

project = env["PROJECT_DIR"]  # noqa: F821
webapp = os.path.normpath(os.path.join(project, "..", "webapp"))
out_path = os.path.join(project, "src", "webapp_files.h")

files = []
for root, _, names in os.walk(webapp):
    for name in sorted(names):
        full = os.path.join(root, name)
        rel = "/" + os.path.relpath(full, webapp).replace(os.sep, "/")
        mime = MIME.get(os.path.splitext(name)[1].lower())
        if mime:
            with open(full, "rb") as f:
                files.append((rel, mime, gzip.compress(f.read(), 9, mtime=0)))
files.sort()

lines = [
    "// Generated by embed_webapp.py from ../webapp at build time. Do not edit.",
    "#pragma once",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "",
    "struct WebFile { const char *path; const char *mime; const uint8_t *data; size_t len; };",
    "",
]
for i, (_, _, data) in enumerate(files):
    body = ",".join(str(b) for b in data)
    lines.append(f"static const uint8_t WEB_FILE_{i}[] = {{{body}}};")
lines.append("")
lines.append("static const WebFile WEB_FILES[] = {")
for i, (path, mime, data) in enumerate(files):
    lines.append(f'  {{"{path}", "{mime}", WEB_FILE_{i}, {len(data)}}},')
lines.append("};")
lines.append(f"static const size_t WEB_FILES_COUNT = {len(files)};")
text = "\n".join(lines) + "\n"

old = open(out_path).read() if os.path.exists(out_path) else None
if text != old:  # unchanged page: no rebuild
    with open(out_path, "w") as f:
        f.write(text)
print(f"embed_webapp: {len(files)} files, {sum(len(d) for _, _, d in files) // 1024} KB gzipped")
